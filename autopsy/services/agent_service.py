def _gen_uuid() -> str:
    return str(uuid.uuid4())


@dataclass
class InvestigationReport:
    """
    Standardized, structured output generated by the Autopsy Investigation Agent.
    """
    report_id: str
    execution_id: str
    trace_id: str
    investigation_status: str  # INVESTIGATING, COMPLETED, INSUFFICIENT_EVIDENCE, FAILED
    affected_components: List[str] = field(default_factory=list)
    observed_failures: List[str] = field(default_factory=list)
    root_cause_candidates: List[Dict[str, Any]] = field(default_factory=list)
    supporting_evidence: List[str] = field(default_factory=list)
    downstream_impact: List[str] = field(default_factory=list)
    diagnosis: Optional[Dict[str, Any]] = None
    uncertainty: str = "SUPPORTED_BY_EVIDENCE"  # SUPPORTED_BY_EVIDENCE, POSSIBLE, INSUFFICIENT_EVIDENCE
    suggested_investigation: List[str] = field(default_factory=list)
    steps_executed: List[Dict[str, Any]] = field(default_factory=list)
    generated_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    def to_dict(self) -> Dict[str, Any]:
        return {
            "report_id": self.report_id,
            "execution_id": self.execution_id,
            "trace_id": self.trace_id,
            "investigation_status": self.investigation_status,
            "affected_components": self.affected_components,
            "observed_failures": self.observed_failures,
            "root_cause_candidates": self.root_cause_candidates,
            "supporting_evidence": self.supporting_evidence,
            "downstream_impact": self.downstream_impact,
            "diagnosis": self.diagnosis,
            "uncertainty": self.uncertainty,
            "suggested_investigation": self.suggested_investigation,
            "steps_executed": self.steps_executed,
            "generated_at": self.generated_at.isoformat() if self.generated_at else None,
        }


class AutopsyInvestigationTools:
    """
    Controlled tool interface exposed to the Investigation Agent.
    Provides narrowly scoped access to execution, trace, span, failure, RCA, and diagnosis queries.
    """

    def __init__(self, db: Session):
        self.db = db
        self.recon_engine = PipelineReconstructionEngine()
        self.failure_service = FailureDetectionService()
        self.rca_engine = RootCauseAnalysisEngine()
        self.diagnosis_service = DiagnosisService()

    def get_execution(self, execution_id: str) -> Optional[Dict[str, Any]]:
        """Retrieves execution record, status, pipeline details, and associated trace IDs."""
        exec_rec = self.db.query(ExecutionModel).filter_by(id=execution_id).first()
        if not exec_rec:
            return None
        traces = self.db.query(TraceModel).filter_by(execution_id=execution_id).all()
        return {
            "execution_id": exec_rec.id,
            "pipeline_id": exec_rec.pipeline_id,
            "status": exec_rec.status,
            "started_at": exec_rec.started_at.isoformat() if exec_rec.started_at else None,
            "ended_at": exec_rec.ended_at.isoformat() if exec_rec.ended_at else None,
            "duration_ms": exec_rec.duration_ms,
            "trace_ids": [t.trace_id for t in traces],
            "attributes": exec_rec.attributes or {},
        }

    def get_trace(self, trace_id: str) -> Optional[Dict[str, Any]]:
        """Retrieves trace timing, root span ID, and total span count."""
        trace_rec = self.db.query(TraceModel).filter_by(trace_id=trace_id).first()
        if not trace_rec:
            return None
        spans_count = self.db.query(SpanModel).filter_by(trace_id=trace_id).count()
        return {
            "trace_id": trace_rec.trace_id,
            "execution_id": trace_rec.execution_id,
            "root_span_id": trace_rec.root_span_id,
            "start_time": trace_rec.start_time.isoformat() if trace_rec.start_time else None,
            "end_time": trace_rec.end_time.isoformat() if trace_rec.end_time else None,
            "duration_ms": trace_rec.duration_ms,
            "total_spans": spans_count,
            "attributes": trace_rec.attributes or {},
        }

    def get_span(self, span_id: str) -> Optional[Dict[str, Any]]:
        """Retrieves specific span attributes, events, error status, and parent/child references."""
        span_rec = self.db.query(SpanModel).filter_by(span_id=span_id).first()
        if not span_rec:
            return None
        return {
            "span_id": span_rec.span_id,
            "trace_id": span_rec.trace_id,
            "parent_span_id": span_rec.parent_span_id,
            "name": span_rec.name,
            "kind": span_rec.kind,
            "start_time": span_rec.start_time.isoformat() if span_rec.start_time else None,
            "end_time": span_rec.end_time.isoformat() if span_rec.end_time else None,
            "duration_ms": span_rec.duration_ms,
            "status_code": span_rec.status_code,
            "status_message": span_rec.status_message,
            "attributes": span_rec.attributes or {},
            "events": span_rec.events or [],
        }

    def get_failures(self, execution_id: str) -> List[Dict[str, Any]]:
        """Retrieves all detected failures for an execution."""
        failures = self.db.query(FailureModel).filter_by(execution_id=execution_id).all()
        result = []
        for f in failures:
            result.append({
                "failure_id": f.id,
                "execution_id": f.execution_id,
                "trace_id": f.trace_id,
                "span_id": f.span_id,
                "failure_type": f.failure_type,
                "severity": f.severity,
                "error_class": f.error_class,
                "description": f.description,
                "evidence_ids": f.evidence_ids or [],
                "root_cause_hypothesis": f.root_cause_hypothesis,
                "attributes": f.attributes or {},
            })
        return result

    def get_root_cause(self, execution_id: str) -> Dict[str, Any]:
        """Runs RCA engine or retrieves candidates for an execution."""
        traces = self.db.query(TraceModel).filter_by(execution_id=execution_id).all()
        if not traces:
            return {"analysis_status": "INSUFFICIENT_EVIDENCE", "candidates": [], "unresolved_failures": []}
        trace_id = traces[0].trace_id
        return self.rca_engine.analyze_and_persist_from_db(trace_id, self.db)

    def get_evidence(self, failure_id: str) -> List[Dict[str, Any]]:
        """Retrieves evidence records attached to a specific failure."""
        failure = self.db.query(FailureModel).filter_by(id=failure_id).first()
        if not failure or not failure.evidence_ids:
            return []
        evidence_records = self.db.query(EvidenceModel).filter(EvidenceModel.id.in_(failure.evidence_ids)).all()
        return [
            {
                "evidence_id": e.id,
                "evidence_type": e.evidence_type,
                "span_id": e.span_id,
                "summary": e.summary,
                "reference_uri": e.reference_uri,
                "metadata_json": e.metadata_json or {},
            }
            for e in evidence_records
        ]

    def generate_diagnosis(self, trace_id: str, use_llm: bool = True) -> Dict[str, Any]:
        """Invokes the existing diagnosis service (Gemini with deterministic fallback)."""
        return self.diagnosis_service.diagnose_and_persist_from_db(trace_id, self.db, use_llm=use_llm)


class AutopsyInvestigationAgent:
    """
    Controlled Investigation Orchestration Agent for Pipeline Autopsy.
    
    Executes a bounded investigation workflow over structured telemetry evidence,
    enforcing max tool call limits, evidence grounding, and graceful failure handling.
    """

    def __init__(
        self,
        tools: AutopsyInvestigationTools,
        max_tool_calls: int = 10,
        use_llm: bool = True,
    ):
        self.tools = tools
        self.max_tool_calls = max_tool_calls
        self.use_llm = use_llm

    def investigate(self, execution_id: str, trace_id: Optional[str] = None) -> InvestigationReport:
        """
        Executes a controlled, bounded investigation for an execution or trace.
        """
        report_id = _gen_uuid()
        steps: List[Dict[str, Any]] = []
        call_count = 0

        def record_step(tool_name: str, args: Dict[str, Any], result_summary: str, success: bool = True):
            nonlocal call_count
            call_count += 1
            steps.append({
                "step_index": call_count,
                "tool": tool_name,
                "args": args,
                "result_summary": result_summary,
                "success": success,
                "timestamp": datetime.now(timezone.utc).isoformat(),
            })

        # Step 1: Identify execution and associated trace
        if call_count >= self.max_tool_calls:
            return self._build_limited_report(report_id, execution_id, trace_id or "unknown", steps)

        try:
            exec_info = self.tools.get_execution(execution_id)
            record_step("get_execution", {"execution_id": execution_id}, f"Found execution: status={exec_info.get('status') if exec_info else 'NOT_FOUND'}")
        except Exception as err:
            record_step("get_execution", {"execution_id": execution_id}, f"Error: {str(err)}", success=False)
            return self._build_failed_report(report_id, execution_id, trace_id or "unknown", steps, f"Tool failure in get_execution: {str(err)}")

        if not exec_info:
            # Handle missing execution
            return InvestigationReport(
                report_id=report_id,
                execution_id=execution_id,
                trace_id=trace_id or "unknown",
                investigation_status="INSUFFICIENT_EVIDENCE",
                observed_failures=["Execution record not found"],
                uncertainty="INSUFFICIENT_EVIDENCE",
                suggested_investigation=["Verify execution ID and telemetry ingestion status."],
                steps_executed=steps,
            )

        resolved_trace_id = trace_id or (exec_info["trace_ids"][0] if exec_info.get("trace_ids") else None)
        if not resolved_trace_id:
            return InvestigationReport(
                report_id=report_id,
                execution_id=execution_id,
                trace_id="unknown",
                investigation_status="INSUFFICIENT_EVIDENCE",
                observed_failures=["No traces correlated with execution"],
                uncertainty="INSUFFICIENT_EVIDENCE",
                suggested_investigation=["Verify trace context propagation."],
                steps_executed=steps,
            )

        # Step 2: Retrieve trace information
        if call_count >= self.max_tool_calls:
            return self._build_limited_report(report_id, execution_id, resolved_trace_id, steps)

        try:
            trace_info = self.tools.get_trace(resolved_trace_id)
            record_step("get_trace", {"trace_id": resolved_trace_id}, f"Retrieved trace with {trace_info.get('total_spans', 0) if trace_info else 0} spans")
        except Exception as err:
            record_step("get_trace", {"trace_id": resolved_trace_id}, f"Error: {str(err)}", success=False)
            return self._build_failed_report(report_id, execution_id, resolved_trace_id, steps, f"Tool failure in get_trace: {str(err)}")

        if not trace_info:
            return InvestigationReport(
                report_id=report_id,
                execution_id=execution_id,
                trace_id=resolved_trace_id,
                investigation_status="INSUFFICIENT_EVIDENCE",
                observed_failures=[f"Trace '{resolved_trace_id}' not found in telemetry store"],
                uncertainty="INSUFFICIENT_EVIDENCE",
                suggested_investigation=["Inspect OTLP ingestion logs."],
                steps_executed=steps,
            )

        # Step 3: Retrieve detected failures
        if call_count >= self.max_tool_calls:
            return self._build_limited_report(report_id, execution_id, resolved_trace_id, steps)

        try:
            failures = self.tools.get_failures(execution_id)
            record_step("get_failures", {"execution_id": execution_id}, f"Retrieved {len(failures)} failure records")
        except Exception as err:
            record_step("get_failures", {"execution_id": execution_id}, f"Error: {str(err)}", success=False)
            return self._build_failed_report(report_id, execution_id, resolved_trace_id, steps, f"Tool failure in get_failures: {str(err)}")

        # Step 4: Retrieve Root Cause Analysis
        if call_count >= self.max_tool_calls:
            return self._build_limited_report(report_id, execution_id, resolved_trace_id, steps)

        try:
            rca_result = self.tools.get_root_cause(execution_id)
            cand_count = len(rca_result.get("candidates", []))
            record_step("get_root_cause", {"execution_id": execution_id}, f"RCA status={rca_result.get('analysis_status')}, candidates={cand_count}")
        except Exception as err:
            record_step("get_root_cause", {"execution_id": execution_id}, f"Error: {str(err)}", success=False)
            return self._build_failed_report(report_id, execution_id, resolved_trace_id, steps, f"Tool failure in get_root_cause: {str(err)}")

        # Step 5: Retrieve Detailed Evidence for primary failures
        all_evidence: List[str] = []
        for f in failures[:3]:  # Limit evidence lookups to stay safely bounded
            if call_count >= self.max_tool_calls:
                break
            try:
                ev_records = self.tools.get_evidence(f["failure_id"])
                record_step("get_evidence", {"failure_id": f["failure_id"]}, f"Retrieved {len(ev_records)} evidence items")
                for ev in ev_records:
                    all_evidence.append(f"[{ev['evidence_type']}] {ev['summary']}")
            except Exception as err:
                record_step("get_evidence", {"failure_id": f["failure_id"]}, f"Error: {str(err)}", success=False)

        # Step 6: Generate Diagnosis via Diagnosis Service (Gemini with deterministic fallback)
        if call_count >= self.max_tool_calls:
            return self._build_limited_report(report_id, execution_id, resolved_trace_id, steps)

        try:
            diagnosis_data = self.tools.generate_diagnosis(resolved_trace_id, use_llm=self.use_llm)
            record_step("generate_diagnosis", {"trace_id": resolved_trace_id, "use_llm": self.use_llm}, f"Generated diagnosis from {diagnosis_data.get('reasoning_source')}")
        except Exception as err:
            record_step("generate_diagnosis", {"trace_id": resolved_trace_id}, f"Error: {str(err)}", success=False)
            diagnosis_data = None

        # Step 7: Assemble Final Investigation Report
        affected_comps = []
        for f in failures:
            svc = f.get("attributes", {}).get("service_name") or "unknown_service"
            op = f.get("attributes", {}).get("operation_name") or "unknown_op"
            affected_comps.append(f"{svc}/{op} (span_id: {f.get('span_id')})")

        observed_fails = [f.get("description", "Failure observed") for f in failures]
        if not observed_fails and not failures:
            observed_fails = ["No failures detected in telemetry"]

        rc_candidates = rca_result.get("candidates", [])
        downstream = []
        for c in rc_candidates:
            for ds in c.get("downstream_impact_spans", []):
                downstream.append(f"{ds.get('operation_name')} ({ds.get('service_name')})")

        uncertainty_state = (
            diagnosis_data.get("uncertainty", "SUPPORTED_BY_EVIDENCE")
            if diagnosis_data
            else ("INSUFFICIENT_EVIDENCE" if not failures else "SUPPORTED_BY_EVIDENCE")
        )

        if uncertainty_state == "INSUFFICIENT_EVIDENCE" or rca_result.get("analysis_status") == "INSUFFICIENT_EVIDENCE":
            investigation_status = "INSUFFICIENT_EVIDENCE"
        else:
            investigation_status = "COMPLETED"

        suggested = (
            diagnosis_data.get("suggested_investigation", [])
            if diagnosis_data
            else [f"Inspect logs for affected spans: {', '.join([f.get('span_id', '') for f in failures])}"]
        )

        return InvestigationReport(
            report_id=report_id,
            execution_id=execution_id,
            trace_id=resolved_trace_id,
            investigation_status=investigation_status,
            affected_components=list(set(affected_comps)),
            observed_failures=observed_fails,
            root_cause_candidates=rc_candidates,
            supporting_evidence=all_evidence or [f.get("description", "") for f in failures],
            downstream_impact=list(set(downstream)),
            diagnosis=diagnosis_data,
            uncertainty=uncertainty_state,
            suggested_investigation=suggested,
            steps_executed=steps,
        )

    def _build_limited_report(self, report_id: str, execution_id: str, trace_id: str, steps: List[Dict[str, Any]]) -> InvestigationReport:
        return InvestigationReport(
            report_id=report_id,
            execution_id=execution_id,
            trace_id=trace_id,
            investigation_status="FAILED",
            observed_failures=[f"Investigation reached maximum tool-call limit ({self.max_tool_calls})"],
            uncertainty="INSUFFICIENT_EVIDENCE",
            suggested_investigation=["Increase max_tool_calls limit or investigate components individually."],
            steps_executed=steps,
        )

    def _build_failed_report(self, report_id: str, execution_id: str, trace_id: str, steps: List[Dict[str, Any]], error_msg: str) -> InvestigationReport:
        return InvestigationReport(
            report_id=report_id,
            execution_id=execution_id,
            trace_id=trace_id,
            investigation_status="FAILED",
            observed_failures=[error_msg],
            uncertainty="INSUFFICIENT_EVIDENCE",
            suggested_investigation=["Check database health and tool connectivity."],
            steps_executed=steps,
        )
